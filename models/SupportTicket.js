/* ============================================================
   FLEXAGO SUPPORT TICKET MODEL

   Shared support-ticket model for:
   - Sender support
   - Traveler support
   - Delivery-related support
   - Admin/support management
============================================================ */

const mongoose = require("mongoose");

/* ============================================================
   SUPPORT NOTE SCHEMA

   Internal/admin notes can be added later without changing
   the main ticket structure.
============================================================ */

const SupportNoteSchema = new mongoose.Schema(
  {
    message: {
      type: String,
      required: true,
      trim: true,
      maxlength: 3000
    },

    addedBy: {
      type: String,
      trim: true,
      default: "admin"
    },

    createdAt: {
      type: Date,
      default: Date.now
    }
  },
  {
    _id: true
  }
);

/* ============================================================
   SUPPORT TICKET SCHEMA
============================================================ */

const SupportTicketSchema = new mongoose.Schema(
  {
    /* ========================================================
       TICKET NUMBER

       Human-friendly ticket number will be generated by the
       controller when the ticket is created.
    ======================================================== */

    ticketNumber: {
      type: String,
      required: true,
      unique: true,
      index: true,
      trim: true
    },

    /* ========================================================
       REQUESTING USER
    ======================================================== */

    userId: {
      type: mongoose.Schema.Types.ObjectId,
      required: true,
      index: true
    },

    userRole: {
      type: String,
      required: true,
      enum: [
        "sender",
        "traveler"
      ],
      index: true
    },

    /* ========================================================
       REQUESTER INFORMATION

       Stored on the ticket so Admin can identify the requester
       without depending entirely on another collection.
    ======================================================== */

    requesterName: {
      type: String,
      trim: true,
      maxlength: 200,
      default: ""
    },

    requesterEmail: {
      type: String,
      trim: true,
      lowercase: true,
      maxlength: 320,
      default: ""
    },

    requesterPhone: {
      type: String,
      trim: true,
      maxlength: 50,
      default: ""
    },

    /* ========================================================
       ISSUE CATEGORY
    ======================================================== */

    category: {
      type: String,
      required: true,
      enum: [
        "account",
        "verification",
        "payment",
        "payout",
        "delivery",
        "chat",
        "safety",
        "technical",
        "other"
      ],
      index: true
    },

    /* ========================================================
       TICKET CONTENT
    ======================================================== */

    subject: {
      type: String,
      required: true,
      trim: true,
      maxlength: 200
    },

    description: {
      type: String,
      required: true,
      trim: true,
      maxlength: 5000
    },

    /* ========================================================
       OPTIONAL DELIVERY REFERENCE

       Used for payment, payout, delivery, chat, and similar
       issues tied to one delivery.
    ======================================================== */

    deliveryId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Delivery",
      default: null,
      index: true
    },

    /* ========================================================
       PRIORITY
    ======================================================== */

    priority: {
      type: String,
      enum: [
        "low",
        "normal",
        "high",
        "urgent"
      ],
      default: "normal",
      index: true
    },

    /* ========================================================
       TICKET STATUS
    ======================================================== */

    status: {
      type: String,
      enum: [
        "open",
        "in_progress",
        "waiting_user",
        "resolved",
        "closed"
      ],
      default: "open",
      index: true
    },

    /* ========================================================
       ADMIN / SUPPORT MANAGEMENT
    ======================================================== */

    assignedTo: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Admin",
      default: null
    },

    supportNotes: {
      type: [SupportNoteSchema],
      default: []
    },

    /* ========================================================
       RESOLUTION
    ======================================================== */

    resolution: {
      type: String,
      trim: true,
      maxlength: 5000,
      default: ""
    },

    resolvedAt: {
      type: Date,
      default: null
    },

    closedAt: {
      type: Date,
      default: null
    },

    /* ========================================================
       USER VISIBILITY

       Allows a ticket to remain in the database while later
       being hidden from normal user-history views if needed.
    ======================================================== */

    visibleToUser: {
      type: Boolean,
      default: true
    }
  },

  /* ==========================================================
     AUTOMATIC TIMESTAMPS

     Adds:
     createdAt
     updatedAt
  ========================================================== */

  {
    timestamps: true
  }
);

/* ============================================================
   INDEXES
============================================================ */

SupportTicketSchema.index({
  userId: 1,
  createdAt: -1
});

SupportTicketSchema.index({
  status: 1,
  createdAt: -1
});

SupportTicketSchema.index({
  category: 1,
  status: 1
});

/* ============================================================
   MODEL EXPORT

   Prevent model recompilation during development/reloads.
============================================================ */

module.exports =
  mongoose.models.SupportTicket ||
  mongoose.model(
    "SupportTicket",
    SupportTicketSchema
  );